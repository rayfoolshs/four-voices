// Suffix hints used when a word is not in the lexicon.
// [regex, language, explanation]
export const SUFFIX_HINTS = [
  [/(tion|sion|ment|ance|ence|ity|ous|ate|ive|ary|ory|al|ic|ify|ize|ise)$/, "la", "Latinate ending"],
  [/(ness|ship|hood|dom|ful|less|ward|wise|ing|ly|er|est)$/, "oe", "Old English ending"],
  [/(ology|ography|ograph|ophone|ometer|ism|ist|itis)$/, "gr", "Greek ending"],
  [/(ette|oir|eur|que|age|ance|ence)$/, "fr", "French ending"],
];

export function lookup(word) {
  const w = word.toLowerCase().replace(/[^a-z'-]/g, "").replace(/^-+|-+$/g, "");
  if (!w) return null;
  if (LEXICON[w]) {
    const [lang, root, gloss, note] = LEXICON[w];
    return { word: w, lang, root, gloss, note, inferred: false };
  }
  for (const [re, lang, why] of SUFFIX_HINTS) {
    if (re.test(w)) {
      return { word: w, lang, root: "—", gloss: why, inferred: true };
    }
  }
  return null;
}
